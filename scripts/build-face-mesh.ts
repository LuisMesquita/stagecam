// Converts MediaPipe's canonical face model (vendor/canonical_face_model.obj, Apache-2.0) into
// web/src/faces/mesh-data.ts: one UV per landmark plus the triangle list.
// Run: node scripts/build-face-mesh.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(import.meta.dirname, '..');
const obj = readFileSync(join(ROOT, 'vendor', 'canonical_face_model.obj'), 'utf8').split('\n');

const uvs: [number, number][] = [];
const vertexUv = new Map<number, number>();
const triangles: number[] = [];
let vertices = 0;

for (const line of obj) {
  const [kind, ...parts] = line.trim().split(/\s+/);
  if (kind === 'v') vertices++;
  else if (kind === 'vt') uvs.push([Number(parts[0]), Number(parts[1])]);
  else if (kind === 'f') {
    for (const corner of parts) {
      const [v, vt] = corner.split('/').map((n) => Number(n) - 1);
      const known = vertexUv.get(v);
      if (known !== undefined && known !== vt) throw new Error(`Vertex ${v} has two UVs`);
      vertexUv.set(v, vt);
      triangles.push(v);
    }
  }
}

if (vertices !== 468 || vertexUv.size !== 468)
  throw new Error(`Unexpected mesh: ${vertices} vertices`);
const perLandmark = Array.from({ length: vertices }, (_, i) => uvs[vertexUv.get(i)!]);
const round = (n: number) => Math.round(n * 1e5) / 1e5;

writeFileSync(
  join(ROOT, 'web', 'src', 'faces', 'mesh-data.ts'),
  `// Generated by scripts/build-face-mesh.ts from MediaPipe's canonical face model (Apache-2.0).
// Index i matches face landmark i. UV origin is bottom-left (OBJ convention).

export const FACE_UV = new Float32Array([${perLandmark.flatMap(([u, v]) => [round(u), round(v)]).join(',')}]);

export const FACE_TRIANGLES = new Uint16Array([${triangles.join(',')}]);
`,
);
console.log(`Wrote ${vertices} UVs and ${triangles.length / 3} triangles`);
